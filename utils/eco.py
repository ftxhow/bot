# utils/eco.py

import random
import hashlib
from typing import List, Dict
from datetime import datetime

def generate_eco_tips(profile: Dict, user_id: str = None) -> List[str]:
    """
    Возвращает 5 уникальных персональных эко-советов на основе профиля пользователя.
    Использует user_id + дату для seed рандомизации, чтобы у разных пользователей
    были разные советы в один и тот же момент времени.
    """

    def _get(key, default=None):
        v = profile.get(key, default)
        return (str(v).strip().lower() if isinstance(v, str) else v)

    # Создаём уникальный seed для каждого пользователя + дату (чтобы советы менялись каждый день)
    today = datetime.now().strftime("%Y-%m-%d")
    seed_str = f"{user_id or 'default'}_{today}_{str(profile)}"
    seed = int(hashlib.md5(seed_str.encode()).hexdigest(), 16) % (10**9)
    rng = random.Random(seed)

    all_tips: List[str] = []

    # ===== ТРАНСПОРТ =====
    transport = _get("transport", "")
    
    TAXI_TIPS = [
        "🚕 Объединяйте поездки и делитесь такси с попутчиками — экономия и экология.",
        "🚕 Выбирайте электро-такси или гибриды, когда есть выбор.",
        "🚕 Для коротких поездок до 2 км лучше пройтись пешком.",
        "🚕 Планируйте маршруты заранее — меньше петляний = меньше выбросов.",
        "🚕 Попробуйте карпулинг (BlaBlaCar) для междугородних поездок.",
        "🚕 Установите приложение для сравнения цен такси — иногда дешевле взять каршеринг.",
    ]
    
    PUBLIC_TRANSPORT_TIPS = [
        "🚌 Отличный экологичный выбор! Общественный транспорт снижает ваш углеродный след.",
        "🚌 Носите многоразовую бутылку — не покупайте воду на станциях.",
        "🚌 Попробуйте электробусы и трамваи — они ещё экологичнее.",
        "🚌 Используйте время в транспорте для чтения электронных книг вместо бумажных.",
        "🚌 Рассмотрите велопрокат для последней мили до работы.",
        "🚌 Если есть выбор, метро энергоэффективнее автобуса.",
    ]
    
    CAR_TIPS = [
        "🚗 Проверяйте давление в шинах раз в месяц — экономия топлива до 3%.",
        "🚗 Глушите двигатель при остановках более 30 секунд.",
        "🚗 Избегайте резких ускорений — плавная езда экономит до 20% топлива.",
        "🚗 Снимите багажник с крыши, если не используете — это +10% расхода.",
        "🚗 Планируйте маршруты вне часа пик — меньше пробок = меньше топлива.",
        "🚗 Рассмотрите установку ГБО — газ дешевле и экологичнее бензина.",
        "🚗 При следующей покупке задумайтесь об электромобиле или гибриде.",
        "🚗 Объединяйте дела в одну поездку вместо нескольких коротких.",
    ]
    
    DRIVER_TIPS = [
        "🚘 Попросите водителя глушить двигатель при долгих ожиданиях.",
        "🚘 Объединяйте все дела в минимум поездок.",
        "🚘 Рекомендуйте водителю курсы экодрайвинга — экономия +15%.",
        "🚘 При замене авто посоветуйте гибрид или электромобиль.",
    ]
    
    if transport in ("такси", "taxi"):
        all_tips.extend(rng.sample(TAXI_TIPS, min(3, len(TAXI_TIPS))))
    elif transport in ("общественный", "public", "общественный транспорт"):
        all_tips.extend(rng.sample(PUBLIC_TRANSPORT_TIPS, min(3, len(PUBLIC_TRANSPORT_TIPS))))
    elif transport in ("своя_машина", "своя машина", "car"):
        all_tips.extend(rng.sample(CAR_TIPS, min(3, len(CAR_TIPS))))
    elif transport in ("водитель", "driver"):
        all_tips.extend(rng.sample(DRIVER_TIPS, min(2, len(DRIVER_TIPS))))

    # ===== ЖИЛЬЁ =====
    housing = _get("housing", "")
    
    PARENTS_TIPS = [
        "🏠 Предложите родителям установить светодиодные лампы — экономия 80% энергии.",
        "🏠 Организуйте дома раздельный сбор хотя бы пластика и бумаги.",
        "🏠 Научите семью выключать воду при чистке зубов — 6 литров/мин экономии.",
        "🏠 Предложите поставить аэраторы на краны — расход воды -50%.",
    ]
    
    RENT_TIPS = [
        "🏠 Используйте умные розетки — отключают технику от сети автоматически.",
        "🏠 Проверьте уплотнители окон — через щели уходит до 30% тепла.",
        "🏠 Стирайте при 30°C — достаточно для большинства вещей, экономия энергии.",
        "🏠 Договоритесь с соседями о совместных закупках — меньше упаковки.",
        "🏠 Сообщайте арендодателю об утечках — экономите воду и деньги.",
    ]
    
    OWN_TIPS = [
        "🏠 Установите двухтарифный счётчик — стирка ночью дешевле.",
        "🏠 Утеплите дом: окупается за 2-3 отопительных сезона.",
        "🏠 Солнечный коллектор для нагрева воды снижает счета на 30%.",
        "🏠 Рассмотрите тепловой насос вместо газового котла.",
        "🏠 Датчики движения на уличном освещении — свет только когда нужен.",
        "🏠 Соберите дождевую воду для полива сада.",
        "🏠 Посадите деревья вокруг дома — естественный кондиционер летом.",
    ]
    
    DORM_TIPS = [
        "🏠 Сохраняйте душ до 5 минут — экономия воды и энергии.",
        "🏠 Выключайте свет и технику, выходя из комнаты.",
        "🏠 Используйте многоразовые контейнеры вместо одноразовой посуды.",
        "🏠 Организуйте с соседями обмен ненужными вещами.",
    ]
    
    if housing in ("с_родителями", "parents"):
        all_tips.extend(rng.sample(PARENTS_TIPS, min(2, len(PARENTS_TIPS))))
    elif housing in ("снимает", "rent"):
        all_tips.extend(rng.sample(RENT_TIPS, min(2, len(RENT_TIPS))))
    elif housing in ("своя", "own"):
        all_tips.extend(rng.sample(OWN_TIPS, min(2, len(OWN_TIPS))))
    elif housing in ("общежитие", "dorm"):
        all_tips.extend(rng.sample(DORM_TIPS, min(2, len(DORM_TIPS))))

    # ===== ДЕТИ =====
    kids = profile.get("kids", 0)
    try:
        kids_num = 4 if str(kids).strip() in ("4+", "4plus") else int(kids)
    except Exception:
        kids_num = 0
        
    KIDS_TIPS = [
        "👶 Покупайте детскую одежду на вырост в секонд-хенде — дети быстро растут.",
        "👶 Передавайте вещи между семьями — экономия и экология.",
        "👶 Попробуйте тканевые подгузники — окупаются за 6 месяцев.",
        "👶 Делайте игрушки из картона и вторсырья — дети любят мастерить.",
        "👶 Книги берите в библиотеке или покупайте электронные.",
        "👶 Учите детей сортировать мусор через игру.",
        "👶 Готовьте детское пюре сами — без упаковки и консервантов.",
        "👶 Используйте тканевые салфетки вместо одноразовых.",
    ]
    
    if kids_num > 0:
        all_tips.extend(rng.sample(KIDS_TIPS, min(2, len(KIDS_TIPS))))

    # ===== БЮДЖЕТ =====
    budget_level = _get("budget_level", "средний")
    
    LOW_BUDGET_TIPS = [
        "💰 Чините вещи вместо покупки новых — YouTube в помощь.",
        "💰 Покупайте продукты у фермеров — дешевле без наценки магазинов.",
        "💰 Шейте сумки-шопперы из старой одежды.",
        "💰 Стеклянные банки — бесплатные контейнеры для круп.",
        "💰 Компостируйте остатки еды — удобрение для цветов бесплатно.",
        "💰 Выращивайте зелень на подоконнике — свежая и без пластика.",
    ]
    
    MEDIUM_BUDGET_TIPS = [
        "💰 Покупайте эко-химию в концентратах с перезаправкой.",
        "💰 Инвестируйте в качественные многоразовые вещи — служат годами.",
        "💰 Поддерживайте локальных производителей — меньше логистики.",
        "💰 Фильтр для воды окупается за 2 месяца против бутылированной.",
        "💰 Установите приложения для отслеживания расхода энергии/воды.",
    ]
    
    HIGH_BUDGET_TIPS = [
        "💰 Инвестируйте в солнечные панели — окупаются за 5-7 лет.",
        "💰 Техника класса A+++ экономит до 50% энергии.",
        "💰 Рассмотрите тепловой насос для отопления.",
        "💰 Электромобиль экономит 70% на топливе.",
        "💰 Поддержите экологические проекты — посадка деревьев, очистка океана.",
        "💰 Офсетируйте свой углеродный след через сертифицированные программы.",
    ]
    
    if budget_level == "низкий":
        all_tips.extend(rng.sample(LOW_BUDGET_TIPS, min(2, len(LOW_BUDGET_TIPS))))
    elif budget_level == "средний":
        all_tips.extend(rng.sample(MEDIUM_BUDGET_TIPS, min(2, len(MEDIUM_BUDGET_TIPS))))
    elif budget_level == "высокий":
        all_tips.extend(rng.sample(HIGH_BUDGET_TIPS, min(2, len(HIGH_BUDGET_TIPS))))

    # ===== СЕМЕЙНЫЙ СТАТУС =====
    status = _get("status", "")
    
    SINGLE_TIPS = [
        "👤 Готовьте порционно и замораживайте — меньше испорченной еды.",
        "👤 Берите еду на работу в многоразовых контейнерах.",
        "👤 Делайте совместные закупки с друзьями — меньше упаковки.",
        "👤 Рассмотрите коливинг — экономия ресурсов и аренды.",
    ]
    
    MARRIED_TIPS = [
        "👫 Согласуйте семейные эко-привычки — вместе проще.",
        "👫 Установите аэраторы на все краны — до 50% экономии воды.",
        "👫 Планируйте меню на неделю — меньше лишних покупок и отходов.",
        "👫 Создайте семейный бюджет на eco-инвестиции (техника, утепление).",
    ]
    
    RELATIONSHIP_TIPS = [
        "💑 Делитесь экопривычками с партнёром — совместные цели сближают.",
        "💑 Ходите на эко-маркеты вместе — меньше упаковки.",
        "💑 Устраивайте свидания на природе с уборкой мусора.",
    ]
    
    DIVORCED_TIPS = [
        "💔 Подайте детям пример экологичного поведения.",
        "💔 Организуйте обмен детскими вещами с бывшим партнёром.",
        "💔 Научите детей экономить ресурсы через игру.",
    ]
    
    if status in ("одинокий", "single"):
        all_tips.extend(rng.sample(SINGLE_TIPS, min(1, len(SINGLE_TIPS))))
    elif status in ("женат_замужем", "married"):
        all_tips.extend(rng.sample(MARRIED_TIPS, min(1, len(MARRIED_TIPS))))
    elif status in ("в_отношениях", "relationship"):
        all_tips.extend(rng.sample(RELATIONSHIP_TIPS, min(1, len(RELATIONSHIP_TIPS))))
    elif status in ("в_разводе", "divorced"):
        all_tips.extend(rng.sample(DIVORCED_TIPS, min(1, len(DIVORCED_TIPS))))

    # ===== ПОЛ =====
    sex = _get("sex", _get("gender", ""))
    
    MALE_TIPS = [
        "🧔 Электробритва экологичнее одноразовых станков.",
        "🧔 Брейтесь с минимумом воды или попробуйте сухое бритьё.",
        "🧔 Используйте кусковое мыло вместо геля в пластике.",
        "🧔 Дезодорант-стик — меньше аэрозольных баллонов.",
    ]
    
    FEMALE_TIPS = [
        "👩 Многоразовые диски для снятия макияжа — 500 ваток экономии/год.",
        "👩 Менструальная чаша или период-трусы — экологичнее прокладок.",
        "👩 Косметика с перезаправляемой упаковкой становится стандартом.",
        "👩 Избегайте косметики с микропластиком (проверяйте состав).",
        "👩 Сухой шампунь сокращает количество мытья головы.",
    ]
    
    if sex in ("м", "m", "male"):
        all_tips.extend(rng.sample(MALE_TIPS, min(1, len(MALE_TIPS))))
    elif sex in ("ж", "f", "female"):
        all_tips.extend(rng.sample(FEMALE_TIPS, min(1, len(FEMALE_TIPS))))

    # ===== ВОЗРАСТ =====
    age = profile.get("age", None)
    try:
        age = int(age) if age is not None else None
    except Exception:
        age = None

    YOUNG_TIPS = [  # < 18
        "🎒 Носи многоразовую бутылку в школу — крутой и экологичный.",
        "🎒 Электросамокат или велик — быстрее и экологичнее маршрутки.",
        "🎒 Цифровые учебники весят меньше — и деревьям легче.",
        "🎒 Сортируй хотя бы батарейки — они очень токсичны.",
    ]
    
    STUDENT_TIPS = [  # 18-25
        "🎓 Секонд-хенд и винтаж — модно и экологично.",
        "🎓 Электронные чеки вместо бумажных — меньше мусора.",
        "🎓 Сами готовьте вместо доставки — здоровее и без упаковки.",
        "🎓 Книги — в библиотеке или электронные.",
        "🎓 Кофе в свою кружку — скидка +экология.",
    ]
    
    ADULT_TIPS = [  # 26-40
        "👔 Участвуйте в местных эко-инициативах.",
        "👔 Экологичная бытовая химия: соода, уксус, мыло.",
        "👔 Покупайте реже, но качественное — служит дольше.",
        "👔 Оформите экологическую подписку на кофе/чай без упаковки.",
        "👔 1 день без мяса в неделю снижает углеродный след на 10%.",
    ]
    
    SENIOR_TIPS = [  # 40+
        "🧓 Обновите технику на A+++ — окупится за 2-3 года.",
        "🧓 Локальные продукты — свежее и с меньшим углеродным следом.",
        "🧓 Передавайте экогривычки внукам — лучшее наследство.",
        "🧓 Отдайте ненужную одежду на благотворительность.",
        "🧓 Сад и огород — своя еда без пластика и пестицидов.",
    ]

    if age is not None:
        if age < 18:
            all_tips.extend(rng.sample(YOUNG_TIPS, min(1, len(YOUNG_TIPS))))
        elif 18 <= age <= 25:
            all_tips.extend(rng.sample(STUDENT_TIPS, min(1, len(STUDENT_TIPS))))
        elif 26 <= age <= 40:
            all_tips.extend(rng.sample(ADULT_TIPS, min(1, len(ADULT_TIPS))))
        else:
            all_tips.extend(rng.sample(SENIOR_TIPS, min(1, len(SENIOR_TIPS))))

    # ===== УНИВЕРСАЛЬНЫЕ СОВЕТЫ (fallback) =====
    UNIVERSAL_TIPS = [
        "🌍 Откажитесь от пластиковых пакетов — одна сумка-шоппер заменяет 500.",
        "🌍 Многоразовая бутылка экономит 150 бутылок в год.",
        "🌍 Выключайте воду во время чистки зубов — 6 литров/мин.",
        "🌍 Печатайте с двух сторон или откажитесь от бумаги совсем.",
        "🌍 Не оставляйте зарядки в розетках — они всё равно потребляют.",
        "🌍 1 кг говядины = 27 кг CO₂. Попробуйте курицу или бобовые.",
        "🌍 Местная сезонная еда — меньше углеродного следа.",
        "🌍 Светодиодные лампы потребляют в 10 раз меньше энергии.",
        "🌍 Стирайте при 30°C — достаточно для большинства вещей.",
        "🌍 Выключайте технику из розетки — standby потребляет до 10% энергии.",
        "🌍 Компостируйте пищевые отходы — даже на балконе.",
        "🌍 Покупайте товары с минимумом упаковки.",
        "🌍 Чините одежду вместо покупки новой.",
        "🌍 Велосипед или пешком — 0 выбросов.",
        "🌍 Сдавайте батарейки и электронику на переработку.",
    ]

    # Удаляем дубликаты
    seen = set()
    unique_tips = []
    for t in all_tips:
        key = t.strip().lower()
        if key not in seen:
            seen.add(key)
            unique_tips.append(t)

    # Добавляем универсальные, если нужно больше
    rng.shuffle(UNIVERSAL_TIPS)
    for t in UNIVERSAL_TIPS:
        if len(unique_tips) >= 5:
            break
        if t.lower() not in seen:
            unique_tips.append(t)
            seen.add(t.lower())

    # Перемешиваем финальный список
    rng.shuffle(unique_tips)
    
    return unique_tips[:5]
